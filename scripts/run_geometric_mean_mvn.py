import time

import numpy as np
import matplotlib.pyplot as plt

from src.simulated_data import random_SPD, random_tangent_vector
from src.mean import geometric_mean_mvn
from src.mvn import exp_map_mvn
from src.distance import dist2_dF


def random_MVNs_exp(
    mu: np.ndarray,
    Sigma: np.ndarray,
    n_mvn: int,
    radius: float,
) -> tuple[np.ndarray, np.ndarray]:
    """
    Generates MVNs P_k = Exp_P(radius * xi_k) around P = N(mu, Sigma) with the
    Fisher-Rao exponential map.

    The tangent vectors are xi_k = (L z_k, L eta_k L^T) with Sigma = L L^T,
    z_k standard Gaussian and eta_k the symmetrical part of a standard
    Gaussian matrix, so that their law does not depend on P up to the affine
    normalization.

    Parameters
    ----------
    mu : ndarray
        Central mean of shape (n_features,).
    Sigma : ndarray
        Central SPD covariance of shape (n_features, n_features).
    n_mvn : int
        Number of MVNs to generate.
    radius : float
        Scale of the tangent vectors.

    Returns
    -------
    means : ndarray
        Means of shape (n_mvn, n_features).
    covariances : ndarray
        SPD covariances of shape (n_mvn, n_features, n_features).
    """
    n_features = mu.size
    L = np.linalg.cholesky(Sigma)
    means = np.zeros((n_mvn, n_features))
    covariances = np.zeros((n_mvn, n_features, n_features))
    for k in range(n_mvn):
        v = radius * L @ np.random.standard_normal(n_features)
        T = radius * L @ random_tangent_vector(n_features, Sigma) @ L.T
        means[k], covariances[k] = exp_map_mvn(mu, Sigma, v, T)
    return means, covariances


def mse_curve_geometric_mvn(
    n_features: int = 3,
    Ns: tuple[int, ...] = (5, 10, 20, 50, 100),
    n_MC: int = 20,
    condition_number: float = 10.0,
    radius: float = 0.1,
) -> tuple[np.ndarray, np.ndarray, float]:
    """
    Monte Carlo MSE curve of the Fisher-Rao geometric mean of MVNs, where the
    MVNs are generated by the Fisher-Rao exponential map around a central MVN.

    Parameters
    ----------
    n_features : int
        Dimension of the MVNs.
    Ns : tuple of int
        Sample sizes N (number of MVNs in the mean).
    n_MC : int
        Number of Monte Carlo iterations.
    condition_number : float
        Condition number of the central covariance (for random_SPD).
    radius : float
        Scale of the tangent vectors around the central MVN.

    Returns
    -------
    Ns_array : ndarray
        Values of N.
    mse : ndarray
        Mean over the n_MC iterations of d_F^2(true center, estimated mean), for each N.
    runtime : float
        Total computation time of the geometric means, in seconds.
    """
    Ns_array = np.array(Ns, dtype=int)
    mu = np.random.standard_normal(n_features)          # Moyenne vraie
    Sigma = random_SPD(n_features, condition_number)     # Covariance vraie
    mse = np.zeros(len(Ns_array))
    runtime = 0.0
    for mc in range(n_MC):
        for i, N in enumerate(Ns_array):
            # 1) générer N MVN P_k = Exp_P(radius * xi_k) autour de P = N(mu, Sigma)
            means, covariances = random_MVNs_exp(mu, Sigma, N, radius)
            # 2) moyenne géométrique de Fisher-Rao, initialisée au centre comme dans le cas SPD
            start = time.perf_counter()
            mean_hat, Sigma_hat = geometric_mean_mvn(means, covariances, init=(mu, Sigma))
            runtime += time.perf_counter() - start
            # 3) erreur en distance de Fisher-Rao au carré
            mse[i] += dist2_dF(mu, Sigma, mean_hat, Sigma_hat)
        print(f"[run_geometric_mean_mvn] Monte Carlo {mc + 1}/{n_MC} done")
    mse /= n_MC
    return Ns_array, mse, runtime


def main() -> None:
    """
    Plots the Monte Carlo MSE of the Fisher-Rao geometric mean of MVNs against N.
    """
    print("[run_geometric_mean_mvn] starting…")

    # ----- paramètres -----
    n_features = 3
    Ns = (5, 10, 20, 50, 100)
    n_MC = 20
    condition_number = 10.0
    radius = 0.1
    seed = 0

    np.random.seed(seed)

    # ----- lancer l'expérience -----
    Ns_array, mse, runtime = mse_curve_geometric_mvn(
        n_features=n_features,
        Ns=Ns,
        n_MC=n_MC,
        condition_number=condition_number,
        radius=radius,
    )

    # Référence asymptotique (petit rayon) : E||xi||^2 / N, avec
    # E||xi||^2 = radius^2 (n + n(n+1)/4) pour la métrique de Fisher canonique.
    reference = radius**2 * (n_features + n_features * (n_features + 1) / 4) / Ns_array

    print(f"  total time of the geometric means: {runtime:.1f} s")
    print("N\tMSE d_F^2\tradius^2 E||xi||^2 / N")
    for N, value, ref in zip(Ns_array, mse, reference):
        print(f"{N}\t{value:.4e}\t{ref:.4e}")
    np.savetxt("output/geometric_mean_mvn_mse.csv", np.column_stack([Ns_array, mse, reference]),
               delimiter=",", header="N,mse_dF2,reference", comments="")

    # ----- tracé matplotlib : N vs MSE (en dB) -----
    plt.figure()
    plt.plot(Ns_array, 10 * np.log10(mse + 1e-300), marker="o", label="Fisher-Rao geometric mean")
    plt.plot(Ns_array, 10 * np.log10(reference), ls="--", c="gray",
             label=r"$r^2\,E\|\xi\|^2/N$ (asymptotic)")
    plt.xscale("log")
    plt.xlabel("N (nombre de MVN, log scale)")
    plt.ylabel(r"MSE $d_F^2$ vs true MVN (dB)")
    plt.title(
        f"Monte Carlo MSE of the Fisher-Rao geometric mean\n"
        f"n_features={n_features}, n_MC={n_MC}, radius={radius}, kappa={condition_number}"
    )
    plt.grid(True)
    plt.legend()
    plt.tight_layout()

    out_path = "output/geometric_mean_mvn_mse.png"
    plt.savefig(out_path, dpi=150)
    print(f"[run_geometric_mean_mvn] saved figure -> {out_path} and data -> output/geometric_mean_mvn_mse.csv")

    plt.show(block=True)
    print("[run_geometric_mean_mvn] done.")


if __name__ == "__main__":
    main()
