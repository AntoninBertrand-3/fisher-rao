import time

import numpy as np
import matplotlib.pyplot as plt

from src.simulated_data import random_SPD, random_MVNs
from src.mean import arithmetic_mean, frechet_mean
from src.distance import dist2_d0, dist2_dF


def mse_curves_MVN_means(
    n_features: int = 3,
    Ns: tuple[int, ...] = (5, 10, 20),
    n_MC: int = 5,
    condition_number: float = 10.0,
    radius: float = 0.3,
) -> tuple[np.ndarray, dict[str, np.ndarray], dict[str, float]]:
    """
    Monte Carlo MSE curves of the arithmetic, d_0 and d_F means of MVNs,
    where the MVNs are generated by random_MVNs around a central N(mu, C).

    Parameters
    ----------
    n_features : int
        Dimension of the MVNs.
    Ns : tuple of int
        Sample sizes N (number of MVNs in the mean).
    n_MC : int
        Number of Monte Carlo iterations.
    condition_number : float
        Condition number of the central covariance C (for random_SPD).
    radius : float
        Spread of the MVNs around N(mu, C).

    Returns
    -------
    Ns_array : ndarray
        Values of N.
    mse : dict of ndarray
        For each method, mean of dist2_dF(true center, estimated mean)
        over the n_MC iterations, for each N.
    timings : dict of float
        Total computation time of each method, in seconds.
    """
    Ns_array = np.array(Ns, dtype=int)
    mu = np.random.standard_normal(n_features)        # Moyenne vraie
    C = random_SPD(n_features, condition_number)       # Covariance vraie
    methods = {
        'arithmetic': arithmetic_mean,
        'd0': lambda means, covs: frechet_mean(means, covs, dist2_d0),
        'dF': lambda means, covs: frechet_mean(means, covs, dist2_dF),
    }
    mse = {name: np.zeros(len(Ns_array)) for name in methods}
    timings = {name: 0.0 for name in methods}
    for mc in range(n_MC):
        for i, N in enumerate(Ns_array):
            # 1) générer N MVN autour de N(mu, C)
            means, covs = random_MVNs(mu, C, N, radius=radius)
            # 2) calculer chaque moyenne et son erreur par rapport au centre
            for name, mean in methods.items():
                start = time.perf_counter()
                m_hat, C_hat = mean(means, covs)
                timings[name] += time.perf_counter() - start
                mse[name][i] += dist2_dF(mu, C, m_hat, C_hat)
        print(f"[run_MVN_means] Monte Carlo {mc + 1}/{n_MC} done")
    for name in mse:
        mse[name] /= n_MC
    return Ns_array, mse, timings


def main() -> None:
    print("[run_MVN_means] starting…")

    # ----- paramètres -----
    n_features = 3
    Ns = (5, 10, 20)
    n_MC = 5
    condition_number = 10.0
    radius = 0.3
    seed = 0

    np.random.seed(seed)

    # ----- lancer l'expérience -----
    Ns_array, mse, timings = mse_curves_MVN_means(
        n_features=n_features,
        Ns=Ns,
        n_MC=n_MC,
        condition_number=condition_number,
        radius=radius,
    )
    for name in mse:
        print(f"  {name:10s} MSE = {np.array2string(mse[name], precision=4)}  time = {timings[name]:.1f}s")

    # ----- tracé matplotlib : N vs MSE (en dB) -----
    plt.figure()
    for name, label in (('arithmetic', 'Arithmetic mean'), ('d0', 'd_0 mean'), ('dF', 'd_F mean')):
        plt.plot(Ns_array, 10 * np.log10(mse[name] + 1e-300), marker="o", label=label)
    plt.xscale("log")
    plt.xlabel("N (nombre de MVN, log scale)")
    plt.ylabel("MSE d_F^2 vs true MVN (dB)")
    plt.title(
        f"Monte Carlo MSE of MVN means\n"
        f"n_features={n_features}, n_MC={n_MC}, radius={radius}, kappa={condition_number}"
    )
    plt.grid(True)
    plt.legend()
    plt.tight_layout()

    out_path = "output/MVN_means_mse.png"
    plt.savefig(out_path, dpi=150)
    print(f"[run_MVN_means] saved figure -> {out_path}")

    plt.show(block=True)
    print("[run_MVN_means] done.")


if __name__ == "__main__":
    main()
